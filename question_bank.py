def get_by_level(level: int) -> list:
    return [q for q in QUESTION_BANK if q["difficulty_level"] == level]


def get_by_id(question_id: str) -> dict | None:
    for q in QUESTION_BANK:
        if q["question_id"] == question_id:
            return q
    return None


def total_by_level() -> dict:
    return {
        1: len(get_by_level(1)),
        2: len(get_by_level(2)),
        3: len(get_by_level(3)),
    }


